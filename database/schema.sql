-- Banco reproduzivel do Sistema de Locacao de Veiculos
-- Execute este arquivo no SQL Editor de um novo projeto Supabase.
-- Nao inclui dados, usuarios, regras RLS ou recursos nao confirmados no banco atual.

create table if not exists public.cliente (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  nome varchar null,
  telefone text null,
  cnh text null,
  categoria_cnh text null,
  cep text null,
  senha_cliente text null
);

create table if not exists public.gerente (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  nome text null,
  email text null,
  senha_gerente text null
);

create table if not exists public.veiculo (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  placa text not null,
  ano smallint null,
  modelo text null,
  marca text null,
  "statusVeiculo" text null,
  tipo_veiculo text null,
  valor_diario numeric null,
  constraint veiculo_placa_key unique (placa)
);

create table if not exists public.locacao (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  data_inicio date null,
  data_fim date null,
  dias_alugados smallint null,
  valor_total numeric null,
  forma_pagamento text null,
  veiculo_placa text not null,
  cliente_id bigint not null,
  constraint locacao_cliente_id_fkey
    foreign key (cliente_id) references public.cliente (id),
  constraint locacao_veiculo_placa_fkey
    foreign key (veiculo_placa) references public.veiculo (placa)
);

alter table public.cliente disable row level security;
alter table public.gerente disable row level security;
alter table public.veiculo disable row level security;
alter table public.locacao disable row level security;

-- Permite que a chave anon/public usada pela aplicacao Java acesse as APIs REST.
grant select, insert, update, delete on table public.cliente to anon, authenticated;
grant select, insert, update, delete on table public.gerente to anon, authenticated;
grant select, insert, update, delete on table public.veiculo to anon, authenticated;
grant select, insert, update, delete on table public.locacao to anon, authenticated;

grant usage, select on sequence public.cliente_id_seq to anon, authenticated;
grant usage, select on sequence public.gerente_id_seq to anon, authenticated;
grant usage, select on sequence public.veiculo_id_seq to anon, authenticated;
grant usage, select on sequence public.locacao_id_seq to anon, authenticated;
